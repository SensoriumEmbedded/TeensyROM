// Menu_Regs.h is the single hand-edited source of truth for the register/enum map shared
// between the Teensy firmware and the C64 assembly code. The region between the "These need
// to match C64 Code" and "End C64 matching" marker comments is mechanically translated into
// ACME assignment lines. Menu_Regs.i is a build output: edit Menu_Regs.h instead, then
// rebuild (`npm run build:c64` regenerates it first, every time).
