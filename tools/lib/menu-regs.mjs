import path from 'node:path';

export const MENU_REGS_H = 'Source/Teensy/MinimalBoot/Common/Menu_Regs.h';
export const MENU_REGS_I = 'Source/C64/MainMenuCRT/source/Menu_Regs.i';

const START_MARKER = 'These need to match C64 Code';
const END_MARKER = 'End C64 matching';
const IOH_ENUM_NAME = 'enumIOHandlers';

