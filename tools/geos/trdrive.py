"""Emit the TR block device driver for the firmware.

    python3 tools/geos/trdrive.py out.h

The driver is assembled twice, a page and a byte apart, and every 16-bit word that moved is an
address of its own, so the firmware can place the code wherever the stock driver has room. Needs acme.
"""

import pathlib
import re
import subprocess
import sys
import tempfile

SOURCE = pathlib.Path(__file__).with_name('trdrive.asm')
BASE = 0x9000
SHIFTED = 0x0101
ENTRIES = ('InitForIO', 'DoneWithIO', 'ExitTurbo', 'PurgeTurbo', 'EnterTurbo', 'ChangeDiskDevice', 'NewDisk',
           'ReadBlock', 'WriteBlock', 'VerWriteBlock', 'SendTSBytes', 'GetDOSError', 'ReadLink')


def assemble(org, tmp):
    out, labels = tmp / f'{org:x}.bin', tmp / f'{org:x}.lbl'
    subprocess.run(['acme', f'-DORG={org}', '-f', 'plain', '-o', str(out), '-l', str(labels), str(SOURCE)],
                   check=True)
    return out.read_bytes(), labels.read_text()


def words(code):
    return [code[i] | code[i + 1] << 8 for i in range(len(code) - 1)]


def relocations(low, high):
    moved = [i for i, (a, b) in enumerate(zip(words(low), words(high))) if (b - a) & 0xffff == SHIFTED]
    return [i for n, i in enumerate(moved) if n == 0 or i != moved[n - 1] + 1]


def entry_offsets(labels):
    found = {m.group(1): int(m.group(2), 16) - BASE for m in re.finditer(r'^\s*(\w+)\s*=\s*\$([0-9a-f]+)', labels, re.M)}
    return [found[name] for name in ENTRIES]


def c_array(name, values, width):
    rows = [values[i:i + 16] for i in range(0, len(values), 16)]
    body = ',\n'.join('   ' + ', '.join(f'0x{v:0{width}x}' for v in row) for row in rows)
    return f'static const uint{width * 4}_t {name}[{len(values)}] PROGMEM = {{\n{body}\n}};\n'


def header():
    with tempfile.TemporaryDirectory() as tmp:
        low, labels = assemble(BASE, pathlib.Path(tmp))
        high, _ = assemble(BASE + SHIFTED, pathlib.Path(tmp))
    relocs = relocations(low, high)
    return (
        '// SPDX-License-Identifier: MIT\n'
        '// Generated by tools/geos/trdrive.py from tools/geos/trdrive.asm; do not edit.\n'
        '#pragma once\n'
        '#include <stdint.h>\n'
        '#ifdef ARDUINO\n'
        '#include <avr/pgmspace.h>\n'
        '#else\n'
        '#define PROGMEM\n'
        '#endif\n\n'
        f'#define TR_DRIVER_BASE 0x{BASE:04x}\n'
        + c_array('TRDriverCode', list(low), 2)
        + c_array('TRDriverRelocations', relocs, 4)
        + c_array('TRDriverEntries', entry_offsets(labels), 4))


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    pathlib.Path(sys.argv[1]).write_bytes(header().encode())
