SCRIPT_DIR = Path(__file__).resolve().parent
SRC_H = SCRIPT_DIR / ".." / "Teensy" / "MinimalBoot" / "Common" / "Menu_Regs.h"
DST_I = SCRIPT_DIR / "MainMenuCRT" / "source" / "Menu_Regs.i"

START_MARKER = "These need to match C64 Code"
END_MARKER = "End C64 matching"
IOH_ENUM_NAME = "enumIOHandlers"

